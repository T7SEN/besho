export interface AdminSettingEntry {
  /** Stable id — used as React key + click telemetry handle. */
  id: string;
  /** Headline. Always shown; ranks highest in match score. */
  title: string;
  /** One-line gloss. Shown under the title; medium match weight. */
  description: string;
  /** Top-level admin page label, e.g. "Diagnostics". */
  page: string;
  /** Optional path inside the page, e.g. "Health · Repair operations". */
  section?: string;
  /** Where the result navigates. Hash anchors are best-effort. */
  href: string;
  /** Synonyms / alternate phrasings to match on. Lowercase, space-sep. */
  keywords: string;
  /** Icon for the result row. */
  Icon: LucideIcon;
}

