// src/lib/admin-settings-index.ts
//
// Static catalog of every Sir-only setting / control across `/admin/*`
// sub-pages. Drives the settings search on the admin landing — the
// shape mirrors a Windows / Android Settings search index: an entry
// per actionable control, not per record.
//
// Constants module — no `'use server'`. Imported by the client
// component `<AdminSettingsSearch>` and rendered offline (no Redis
// roundtrip). When you add a new setting / repair tool / admin
// surface, add an entry here too.

